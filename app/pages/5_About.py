st.subheader("1. Problem Statement")
st.markdown("""
Deploying real-time Predictive Maintenance (PdM) for industrial robotic equipment is commonly blocked by three core challenges:
1. **Scarcity of Run-to-Failure Factory Logs:** Industrial robots are maintained conservatively; proprietary failure datasets are closely guarded.
2. **Expensive Sensing Hardware:** Deploying high-frequency acoustic emissions and high-bandwidth DAQs across multiple robots requires prohibitive capital expenditure.
3. **GPU Infrastructure Overhead:** Many deep learning models demand server-class hardware, creating latency and bandwidth bottlenecks for real-time factory floor deployment.

**The Solution:** This simulator uses physics-inspired digital twin modeling to synthesize run-to-failure kinematics and validates that **lightweight CPU models** (XGBoost + FFT) achieve industrial-grade reliability while fitting inside edge budgets (< 50 ms latency on Raspberry Pi 4 hardware).
""")

